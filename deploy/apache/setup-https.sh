#!/bin/sh
# One-time HTTPS setup for the Kanban stacks behind an existing Apache.
# Run as root on the server:  sudo sh setup-https.sh [public-ip]
# Adds two name-based virtual hosts (sslip.io names of the public IP), gets
# Let's Encrypt certificates for them and leaves every other site untouched.
set -eu
IP=${1:-37.194.184.235}
STAGING=staging.$IP.sslip.io
PRODUCTION=kanban.$IP.sslip.io
CONF=/etc/apache2/sites-available/kanban.conf

vhost() {
	name=$1 web=$2 grafana=$3
	cat <<EOT
<VirtualHost *:80>
    ServerName $name
    ProxyPreserveHost On
    ProxyRequests Off
    # The web container trusts X-Real-IP from the proxy: one rate-limit bucket per client.
    RequestHeader set X-Real-IP "%{REMOTE_ADDR}s"
    RequestHeader set X-Forwarded-Proto "https"
    Header always set Strict-Transport-Security "max-age=31536000"
    LimitRequestBody 12582912
    ProxyTimeout 3600
    ProxyPass /grafana/ http://127.0.0.1:$grafana/grafana/
    ProxyPassReverse /grafana/ http://127.0.0.1:$grafana/grafana/
    ProxyPass / http://127.0.0.1:$web/ upgrade=websocket
    ProxyPassReverse / http://127.0.0.1:$web/
    ErrorLog \${APACHE_LOG_DIR}/kanban-error.log
    CustomLog \${APACHE_LOG_DIR}/kanban-access.log combined
</VirtualHost>

EOT
}

{
	echo "# Kanban Lab: staging and production (generated by setup-https.sh)"
	vhost "$STAGING" 8101 3101
	vhost "$PRODUCTION" 8102 3102
} > "$CONF"

a2enmod proxy proxy_http headers rewrite ssl >/dev/null
a2ensite kanban >/dev/null
apache2ctl configtest
systemctl reload apache2

# certbot copies the virtual hosts to HTTPS ones and redirects HTTP to HTTPS.
certbot --apache --non-interactive --agree-tos --redirect --cert-name kanban -d "$STAGING" -d "$PRODUCTION"
systemctl reload apache2

echo "https://$STAGING  https://$PRODUCTION"
